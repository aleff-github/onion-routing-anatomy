"""Laboratory 5 — streams and flow control.

References: tor-spec, "Opening streams and transmitting data", "Closing streams",
"Flow control"; proposal 324 (congestion control, SENDME, and XON/XOFF).
The circuit negotiated congestion control with the exit: there are no SENDME messages
at stream level; outgoing circuit SENDMEs are generated by Circuit.count_received_data().
Teaching module: use only on the book's private laboratory network.
Single-stream teaching model: no multiplexing, inbound circuit SENDME
authentication or sender-side package-window tracking; not a full Tor client.
"""
from __future__ import annotations

import ipaddress
import struct
from dataclasses import dataclass, field

from .cells import RELAY_DATA_MAX, RelayCommand, RelayMessage
from .circuit import Circuit, CircuitError

END_REASONS = {1: "MISC", 2: "RESOLVEFAILED", 3: "CONNECTREFUSED", 4: "EXITPOLICY",
              5: "DESTROY", 6: "DONE", 7: "TIMEOUT", 8: "NOROUTE", 9: "HIBERNATING",
              10: "INTERNAL", 11: "RESOURCELIMIT", 12: "CONNRESET", 13: "TORPROTOCOL",
              14: "NOTDIRECTORY"}


def begin_body(address: str, port: int, flag: int = 0) -> bytes:
    """ASCII NUL-terminated ADDRPORT; optional FLAGS (bits 1–3 only)."""
    if not isinstance(address, str) or not address or "\x00" in address:
        raise ValueError("Address must be nonempty text without NUL")
    if any(ord(ch) <= 32 or ord(ch) == 127 for ch in address):
        raise ValueError("Address may not contain spaces or control characters")
    try:
        address.encode("ascii")
    except UnicodeEncodeError as exc:
        raise ValueError("ADDRPORT must be ASCII (encode international domains as IDNA)") from exc
    if ":" in address or "[" in address or "]" in address:
        if not (address.startswith("[") and address.endswith("]")):
            raise ValueError("IPv6 addresses must be enclosed in square brackets")
        try:
            ipaddress.IPv6Address(address[1:-1])
        except ValueError as exc:
            raise ValueError("Invalid IPv6 address") from exc
    if type(port) is not int or not 1 <= port <= 65535:
        raise ValueError("Port must be an integer between 1 and 65535")
    if type(flag) is not int or not 0 <= flag <= 7:
        raise ValueError("FLAGS must use only bits 1–3")
    body = f"{address.lower()}:{port}".encode("ascii") + b"\x00"
    if flag:
        body += struct.pack(">I", flag)
    if len(body) > RELAY_DATA_MAX:
        raise ValueError("BEGIN body exceeds maximum relay payload")
    return body


def _end_reason(data: bytes) -> str:
    reason = data[0] if data else 1   # Empty RELAY_END means REASON_MISC.
    return END_REASONS.get(reason, f"UNKNOWN({reason})")


@dataclass
class StreamRegistry:
    received_data: int = 0
    data_cells: int = 0
    others: list[str] = field(default_factory=list)


class Stream:
    def __init__(self, circ: Circuit, stream_id: int):
        if type(stream_id) is not int or not 1 <= stream_id <= 65535:
            raise CircuitError("StreamID must be a nonzero 16-bit integer")
        self.circ, self.id = circ, stream_id
        self.reg = StreamRegistry()
        self.closed = False
        self.opened = False

    def open(self, address: str, port: int) -> bytes:
        if self.closed or self.opened:
            raise CircuitError("stream already opened or closed")
        self.circ.send(RelayMessage(RelayCommand.BEGIN, self.id, begin_body(address, port)))
        while True:
            _, msg = self._next()
            if msg.command == RelayCommand.DROP:
                continue
            if msg.command == RelayCommand.END:
                self.closed = True
                raise CircuitError(f"BEGIN rejected: {_end_reason(msg.data)}")
            if msg.command != RelayCommand.CONNECTED:
                raise CircuitError(f"unexpected response to BEGIN: {msg.command}")
            self.opened = True
            return msg.data

    def send(self, data: bytes) -> None:
        if self.closed or not self.opened:
            raise CircuitError("cannot send on an unopened or closed stream")
        if not isinstance(data, (bytes, bytearray, memoryview)):
            raise TypeError("data must be bytes-like")
        data = bytes(data)
        for i in range(0, len(data), RELAY_DATA_MAX):
            self.circ.send(RelayMessage(RelayCommand.DATA, self.id, data[i:i + RELAY_DATA_MAX]))

    def receive_all(self) -> bytes:
        """Read DATA until END; account for outbound circuit SENDMEs."""
        if not self.opened:
            raise CircuitError("stream is not open")
        parts = []
        while not self.closed:
            _, msg = self._next()
            if msg.command == RelayCommand.DATA:
                parts.append(msg.data)
                self.reg.received_data += len(msg.data)
                self.reg.data_cells += 1
                self.circ.count_received_data()
            elif msg.command == RelayCommand.END:
                self.closed = True
                self.reg.others.append(f"END {_end_reason(msg.data)}")
            elif msg.command == RelayCommand.DROP:
                continue
            else:
                known = RelayCommand._value2member_map_.get(msg.command)
                self.reg.others.append(known.name if known else f"UNKNOWN_{msg.command}")
        return b"".join(parts)

    def _next(self):
        hop, msg = self.circ.receive()
        if msg.stream_id == 0:
            if msg.command == RelayCommand.DROP:
                return hop, msg
            if msg.command == RelayCommand.SENDME:
                # Do not silently accept inbound SENDME without window/digest verification.
                raise CircuitError("incoming circuit SENDME: send-window and digest validation not implemented")
            raise CircuitError(f"unexpected circuit-control relay command: {msg.command}")
        if msg.stream_id != self.id:
            raise CircuitError(f"message for an unknown stream {msg.stream_id}")
        return hop, msg

    def close(self) -> None:
        if not self.closed:
            if not self.opened:
                raise CircuitError("stream is not open")
            self.circ.send(RelayMessage(RelayCommand.END, self.id, bytes([6])))  # DONE
            self.closed = True
